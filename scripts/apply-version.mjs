import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const versionFile = resolve(root, "..", "VERSION");
const rawVersion = readFileSync(versionFile, "utf8").trim().replace(/^v/i, "");
const match = rawVersion.match(/^(\d+)\.(\d+)\.(\d+)(?:[-+].*)?$/);
if (!match) {
  throw new Error(`VERSION must be semver, got: ${rawVersion}`);
}
const [, major, minor, patch] = match;
const version = `${Number(major)}.${Number(minor)}.${Number(patch)}`;
const versionCode =
  Number(major) * 1_000_000 + Number(minor) * 1_000 + Number(patch);

function writeJson(path, mutate) {
  const full = resolve(root, path);
  const value = JSON.parse(readFileSync(full, "utf8"));
  mutate(value);
  writeFileSync(full, `${JSON.stringify(value, null, 2)}\n`);
}

function setCargoVersion(path) {
  const full = resolve(root, path);
  const lines = readFileSync(full, "utf8").split(/\r?\n/);
  let section = "";
  for (let index = 0; index < lines.length; index += 1) {
    const trimmed = lines[index].trim();
    if (trimmed.startsWith("[") && trimmed.endsWith("]")) {
      section = trimmed.slice(1, -1);
      continue;
    }
    if (
      (section === "workspace.package" || section === "package") &&
      /^version\s*=/.test(trimmed)
    ) {
      lines[index] = `version = "${version}"`;
    }
  }
  writeFileSync(full, lines.join("\n"));
}

writeJson("package.json", (value) => {
  value.version = version;
});
writeJson("src-tauri/tauri.conf.json", (value) => {
  value.version = version;
});
setCargoVersion("src-tauri/Cargo.toml");

const androidProperties = resolve(
  root,
  "src-tauri/gen/android/app/tauri.properties",
);
mkdirSync(dirname(androidProperties), { recursive: true });
writeFileSync(
  androidProperties,
  `// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n` +
    `tauri.android.versionName=${version}\n` +
    `tauri.android.versionCode=${versionCode}\n`,
);

console.log(`Applied version ${version} (Android versionCode ${versionCode})`);
