fn t2s() -> &'static HashMap<char, char> {
    static MAP: OnceLock<HashMap<char, char>> = OnceLock::new();
    MAP.get_or_init(|| PAIRS.iter().copied().collect())
}

fn s2t() -> &'static HashMap<char, char> {
    static MAP: OnceLock<HashMap<char, char>> = OnceLock::new();
    MAP.get_or_init(|| PAIRS.iter().map(|(t, s)| (*s, *t)).collect())
}

pub fn is_valid_direction(direction: i32) -> bool {
    direction == DIRECTION_T2S || direction == DIRECTION_S2T
}

pub fn convert(text: &str, direction: i32) -> String {
    match direction {
        DIRECTION_T2S => {
            let map = t2s();
            text.chars()
                .map(|c| map.get(&c).copied().unwrap_or(c))
                .collect()
        }
        DIRECTION_S2T => {
            let map = s2t();
            text.chars()
                .map(|c| map.get(&c).copied().unwrap_or(c))
                .collect()
        }
        _ => text.to_string(),
    }
}

